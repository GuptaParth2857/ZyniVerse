/**
 * ZyniVerse config plugin — restricts the release APK to real device ABIs.
 *
 * React Native's template ships all four ABIs:
 *     reactNativeArchitectures=armeabi-v7a,arm64-v8a,x86,x86_64
 *
 * `x86` and `x86_64` exist only for the Android emulator. No phone Uptodown
 * distributes to runs them, and they were adding 28.5 MB — over 40% of the APK
 * — to every user's download.
 *
 * Both ARM ABIs are kept deliberately: `arm64-v8a` covers essentially every
 * phone made since ~2015, but 32-bit `armeabi-v7a` devices are still common in
 * the budget markets Uptodown serves. Dropping it would lock those users out.
 *
 * Two separate places need changing, because they do different jobs:
 *
 *   1. `gradle.properties` -> `reactNativeArchitectures`
 *      Only consulted by modules that build native code themselves (Reanimated,
 *      RN codegen). Saves build time by not compiling x86. On its own it does
 *      NOT change what ends up in the APK.
 *
 *   2. `app/build.gradle` -> `defaultConfig { ndk { abiFilters } }`
 *      This is what actually strips the .so files. Without it the dependency
 *      AARs contribute every ABI and the APK stays fat regardless of (1).
 *
 * `android/` is gitignored and regenerated by `expo prebuild`, so editing those
 * files by hand does not survive a clean prebuild. This plugin runs on every
 * prebuild / `eas build` instead.
 */
const { withAppBuildGradle, withGradleProperties } = require('@expo/config-plugins');

const ARCHITECTURES = ['armeabi-v7a', 'arm64-v8a'];

// Greppable marker so re-running the plugin is a no-op.
const MARKER = 'zyniverse-abi-filters';

function withAbiFilters(config) {
  return withAppBuildGradle(config, (configProps) => {
    const contents = configProps.modResults.contents;

    if (contents.includes(MARKER)) return configProps;

    const block =
      `        // ${MARKER} — real devices only, x86/x86_64 are emulator-only.\n` +
      `        ndk {\n` +
      ARCHITECTURES.map((abi) => `            abiFilters "${abi}"\n`).join('') +
      `        }\n`;

    const match = /\n(\s*)defaultConfig\s*\{/.exec(contents);
    if (!match) {
      throw new Error(
        `withAndroidArchitectures: could not find a \`defaultConfig\` block in app/build.gradle.`
      );
    }

    const insertAt = match.index + match[0].length;
    configProps.modResults.contents =
      contents.slice(0, insertAt) + '\n' + block + contents.slice(insertAt);

    return configProps;
  });
}

function withArchitecturesProperty(config) {
  return withGradleProperties(config, (configProps) => {
    const properties = configProps.modResults;
    const value = ARCHITECTURES.join(',');

    const existing = properties.find(
      (item) => item.type === 'property' && item.key === 'reactNativeArchitectures'
    );

    if (existing) {
      existing.value = value;
    } else {
      properties.push({ type: 'property', key: 'reactNativeArchitectures', value });
    }

    return configProps;
  });
}

module.exports = function withAndroidArchitectures(config) {
  return withAbiFilters(withArchitecturesProperty(config));
};